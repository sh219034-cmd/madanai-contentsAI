/**
 * 各プロンプトの先頭付近に置く、情報の優先順位の明示。
 * 矛盾が生じた場合は番号の若い方を優先する。
 */
export function buildPromptPriorityNotice(): string {
  return `【情報の優先順位】矛盾する場合は番号の若い方を優先すること。
①安全性・事実性（根拠のない断定・成果保証・存在しない実績の禁止）
②ユーザー入力の内容
③マダナイのブランド情報
④このあとのマーケティング原則
⑤選択済みの戦略（コンテンツ生成・再生成の場合）
⑥各媒体（PDF/LINE/SNS等）の出力ルール`;
}

/**
 * 集客・LP構築論の中核原則（要点版）。全プロンプト共通。
 */
export function buildMarketingPrinciplesSection(): string {
  return `【マーケティング原則（要点）】
・集客の4原則: ターゲット(誰に)・ベネフィット(どんな未来)・根拠(なぜ信じられるか)・タイミング(媒体・配信時期・見込み客の検討段階。LP単体では完全に操作できないが考慮する)
・戦略の階層: 文章表現やデザインより、誰に届けるか・どの媒体を使うか・どんな関係性か・なぜこの事業をするかという上位戦略を優先する
・理念と人間関係: 機能説明より、なぜこの事業をしているか・どんな未来を作りたいか・顧客とどんな関係を築きたいかを重視し、共感と信頼につなげる
・新規獲得とリピート: 新規獲得だけでなく、LINE・メール・保守・継続支援・再購入・紹介など顧客との継続的な関係づくりも考慮する
・ターゲット設定: 不特定多数ではなく特定の1人へ手紙を書くように、誰が・どんな状況で・何に困り・何を不安に感じ・どんな未来を望むかまで具体化する
・ベネフィット: 機能やスペックでなく利用後にどう変わるかを重視し、感情的・機能的・経済的・時間的・社会的の複数視点で考える
・根拠: ベネフィットには必ず根拠(実績・お客様の声・事例・写真・制作過程・専門性・比較・数値・仕組み・第三者評価等)を組み合わせる。根拠のない断定は禁止
・抽象と具体: 抽象(感情・未来を動かす)と具体(数字・事例・手順で納得させる)を組み合わせる。基本構成は「抽象で惹きつける→具体で納得させる→再び未来を見せる→行動を促す」
・社会的証明: 実績・お客様の声・事例・写真・数字・権威性を信頼のために活用する。存在しない実績や声は作らない
・新しさ: 「新登場」「リニューアル」等の新規性は事実である場合のみ使う
・価格の見せ方: 価格は単独で見せず、含まれるもの・得られる未来・他の選択肢との違い・追加料金の有無・安心材料と合わせて説明する。誤認させる表現は使わない
・認知段階への配慮: 読み手の状態(未認知/課題認知/解決策認知/サービス認知/比較検討/購入直前/既存顧客)を踏まえ、既に知っていることを最初から繰り返さない
・ビジュアル: 見た目が重要な内容は文章だけで説明せず、事例・写真・図解等の活用を提案する
・SNS導線: 投稿は拡散/信頼構築/理解促進/行動喚起の役割を分け、毎回リンクを貼るのではなくプロフィール・固定投稿・コメント欄・LINE等へ自然に誘導する
・SEO（該当する場合）: 大きなキーワードだけでなく、具体的な悩みや用途を拾うロングテールの視点も考慮する
・心理学の扱い: 用語の乱用ではなく、読み手の理解・感情・意思決定を助ける目的でのみ参考にする`;
}

/**
 * 戦略候補の分析観点。戦略分析プロンプト(strategy-prompt.ts)専用。
 */
export function buildStrategyAnalysisPrinciplesSection(): string {
  return `【戦略候補の分析観点】
各戦略候補は、切り口の名称を出すだけでなく、以下を踏まえて検討すること。
・ターゲット（誰が、どんな状況で、何に困り、何を不安に感じ、どんな未来を望むか）
・認知段階（未認知/課題認知/解決策認知/サービス認知/比較検討/購入直前/既存顧客のどこにいるか）
・中心ベネフィット（感情的・機能的・経済的・時間的・社会的のどれを中心に据えるか）
・必要な根拠（その訴求に説得力を持たせるために何が必要か）
・狙う心理
・適した媒体・適したタイミング（LP/LINE/SNS等のどれに強く、いつ届けるべきか）
・抽象と具体の使い分け方針
・CTAまでの流れ
・リピート・継続導線（一度きりの反応で終わらせない工夫）
おすすめ戦略の選定理由(recommendationReason)にも、これらの観点を踏まえた説明を含めること。`;
}

/**
 * 生成物（PDF/LINE/SNS等）の整合性チェックと追加の禁止事項。
 * コンテンツ生成・部分再生成のシステムプロンプト(madanai-system-prompt.ts)専用。
 * 既存の【文章の原則】【禁止表現】と重複する項目（根拠のない数字・成果保証等）は
 * ここでは繰り返さず、そこにない観点のみを追加する。
 */
export function buildContentConsistencyChecklist(): string {
  return `【生成物の整合性チェック（内部的に確認してから出力すること）】
ターゲット → 悩み → ベネフィット → 根拠 → 構成 → CTA の流れが一貫しているか、
特にターゲットとベネフィット、ベネフィットと根拠、内容とCTAがずれていないかを確認すること。
出力前に以下を自己点検すること：
1.誰向けか明確か 2.ベネフィットが未来として伝わるか 3.根拠が不足していないか
4.抽象と具体が両方あるか 5.認知段階に合っているか 6.同じ説明を繰り返していないか
7.CTAが自然か 8.継続・リピート導線も考慮されているか 9.根拠のない断定がないか
10.マダナイが単なる制作会社に見えていないか

【追加の禁止事項】
・存在しない実績やお客様の声を作らない
・認知段階を無視して毎回同じ型を使わない
・「こんなお悩みありませんか？」を毎回機械的に使わない
・機能説明だけで終わらない
・抽象表現だけで具体性がない文章にしない
・具体情報だけで感情や未来が伝わらない文章にしない
・どの業種にも同じ文章を使い回さない
・心理学用語を権威付けのためだけに使わない`;
}
