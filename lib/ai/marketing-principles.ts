/**
 * 各プロンプトの先頭付近に置く、情報の優先順位の明示。
 * 矛盾が生じた場合は番号の若い方を優先する。
 */
export function buildPromptPriorityNotice(): string {
  return `【情報の優先順位】矛盾する場合は番号の若い方を優先すること。
①安全性・事実性（根拠のない断定・成果保証・存在しない実績の禁止）
②ユーザー入力の内容
③マダナイのブランド情報
④このあとのマーケティング原則
⑤選択済みの戦略（コンテンツ生成・再生成の場合）
⑥各媒体（PDF/LINE/SNS等）の出力ルール`;
}

/**
 * 集客・LP構築論の中核原則（要点版）。全プロンプト共通。
 */
export function buildMarketingPrinciplesSection(): string {
  return `【マーケティング原則（要点）】
・集客の4原則: ターゲット(誰に)・ベネフィット(どんな未来)・根拠(なぜ信じられるか)・タイミング(媒体・配信時期・見込み客の検討段階。LP単体では完全に操作できないが考慮する)
・戦略の階層: 文章表現やデザインより、誰に届けるか・どの媒体を使うか・どんな関係性か・なぜこの事業をするかという上位戦略を優先する
・理念と人間関係: 機能説明より、なぜこの事業をしているか・どんな未来を作りたいか・顧客とどんな関係を築きたいかを重視し、共感と信頼につなげる
・新規獲得とリピート: 新規獲得だけでなく、LINE・メール・保守・継続支援・再購入・紹介など顧客との継続的な関係づくりも考慮する
・ターゲット設定: 不特定多数ではなく特定の1人へ手紙を書くように、誰が・どんな状況で・何に困り・何を不安に感じ・どんな未来を望むかまで具体化する
・ベネフィット: 機能やスペックでなく利用後にどう変わるかを重視し、感情的・機能的・経済的・時間的・社会的の複数視点で考える
・根拠: ベネフィットには必ず根拠(実績・お客様の声・事例・写真・制作過程・専門性・比較・数値・仕組み・第三者評価等)を組み合わせる。根拠のない断定は禁止
・抽象と具体: 抽象(感情・未来を動かす)と具体(数字・事例・手順で納得させる)を組み合わせる。基本構成は「抽象で惹きつける→具体で納得させる→再び未来を見せる→行動を促す」
・社会的証明: 実績・お客様の声・事例・写真・数字・権威性を信頼のために活用する。存在しない実績や声は作らない
・新しさ: 「新登場」「リニューアル」等の新規性は事実である場合のみ使う
・価格の見せ方: 価格は単独で見せず、含まれるもの・得られる未来・他の選択肢との違い・追加料金の有無・安心材料と合わせて説明する。誤認させる表現は使わない
・認知段階への配慮: 読み手の状態(未認知/課題認知/解決策認知/サービス認知/比較検討/購入直前/既存顧客)を踏まえ、既に知っていることを最初から繰り返さない
・ビジュアル: 見た目が重要な内容は文章だけで説明せず、事例・写真・図解等の活用を提案する
・SNS導線: 投稿は拡散/信頼構築/理解促進/行動喚起の役割を分け、毎回リンクを貼るのではなくプロフィール・固定投稿・コメント欄・LINE等へ自然に誘導する
・SEO（該当する場合）: 大きなキーワードだけでなく、具体的な悩みや用途を拾うロングテールの視点も考慮する
・心理学の扱い: 用語の乱用ではなく、読み手の理解・感情・意思決定を助ける目的でのみ参考にする`;
}

/**
 * 出力を確定する前の共通レビュー観点。戦略決定前・コンテンツ生成前の
 * 両方で同じ7項目を使う（企画会議で最終確認するイメージ）ため、
 * 文言をここに1箇所だけ持つ。
 */
export function buildPreOutputReviewChecklist(): string {
  return `・誰向けか明確か　・ベネフィットは未来として伝わるか　・機能説明だけになっていないか
・根拠が不足していないか　・抽象と具体が両方あるか　・競合との差別化があるか
・マダナイらしさがあるか（単なる制作会社の提案に見えていないか）`;
}

/**
 * 戦略候補の分析観点。戦略分析プロンプト(strategy-prompt.ts)専用。
 * 「マーケティング責任者が企画会議で検討するレベル」の深さを持たせるため、
 * ターゲットの解像度・競合分析・USPを明示的に含める。
 */
export function buildStrategyAnalysisPrinciplesSection(): string {
  return `【戦略候補を決める前に、内部で必ず検討すること（企画会議レベルの深さで）】
各戦略候補は、「共感型」のような切り口の名称を出すだけでは不十分。以下の順で内部的に検討したうえで、
その結果を反映した候補を出力すること（検討の全文をそのまま出力に含める必要はない）。

①ターゲットの解像度: 年齢層・性別・職業/業種・売上規模・ITリテラシー・具体的な悩み・
  本音（人に言いにくい本心）・理想（叶えたい未来）まで、入力内容から読み取れる範囲で具体化する
②認知段階: 未認知/課題認知/解決策認知/サービス認知/比較検討/購入直前/既存顧客のどこにいるか
③競合分析: このサービスを検討する人が、何と比較するか・何を不安に思うか・何で迷うか
④USP: 競合ではなくマダナイを選ぶ理由は何か
⑤ベネフィット: 感情・時間・お金・信用・売上・働き方・人生・家族など多角的な観点で、
  内部では最低20個相当を洗い出したうえで、各候補の中心ベネフィットに絞り込む
⑥根拠: 中心ベネフィットに対して、実績・事例・写真・専門性・ストーリー等どんな根拠が必要かを考える。
  入力内容に根拠が不足している場合は、断定はせず「必要な根拠」として扱う
⑦CTAまでの流れ: 最も自然に行動へつながる導線
⑧適した媒体・適したタイミング（LP/LINE/SNS等のどれに強く、いつ届けるべきか）
⑨抽象と具体の使い分け方針
⑩リピート・継続導線（一度きりの反応で終わらせない工夫）

おすすめ戦略の選定理由(recommendationReason)にも、これらの検討を踏まえた説明を含めること。

【戦略決定前の内部レビュー】
候補を確定する前に、以下を自問し、満たしていなければ候補を練り直すこと。
${buildPreOutputReviewChecklist()}`;
}

/**
 * コンテンツ生成の前に行う、選択済み戦略に基づく深掘り分析。
 * madanai-system-prompt.ts(コンテンツ生成)専用。戦略候補選定時の分析
 * (buildStrategyAnalysisPrinciplesSection)と同じ観点を、既に選ばれた
 * 戦略1件に対して、実際の文章に落とし込むレベルまで具体化する。
 */
export function buildGenerationDeepAnalysisSection(): string {
  return `【本文を書く前に、内部で必ず検討すること（企画会議レベルの深さで）】
ユーザー入力と「採用する戦略」をもとに、本文を書き始める前に以下を内部的に検討すること
（検討の全文をそのまま出力に含める必要はない）。

①ターゲットの解像度: 年齢層・性別・職業/業種・売上規模・ITリテラシー・具体的な悩み・
  本音（人に言いにくい本心）・理想（叶えたい未来）
②認知段階: 未認知/課題認知/解決策認知/サービス認知/比較検討/購入直前/既存顧客のどこにいるか
③競合分析: 読み手が何と比較し、何を不安に思い、何で迷っているか
④USP: 競合ではなくマダナイを選ぶ理由
⑤ベネフィット: 感情・時間・お金・信用・売上・働き方・人生・家族など多角的な観点で、
  内部では最低20個相当を洗い出したうえで、本文に使う主要なものへ絞り込む
⑥根拠: 使う予定の各ベネフィットに、実績・事例・写真・専門性・ストーリー等の根拠を割り当てる。
  入力内容に根拠が不足している場合は断定せず、「必要な根拠」として自然に触れる程度にとどめる
⑦CTA設計: 最も自然に行動へつながる導線

【生成前レビュー】
本文を書き始める前に、以下を自問すること。
${buildPreOutputReviewChecklist()}`;
}

/**
 * 生成後にAI自身が内部で採点し、基準に満たなければ出力前に自分で
 * 修正する仕組み。採点結果はユーザーへは表示しない（内部判断専用）。
 */
export function buildGenerationSelfReviewSection(): string {
  return `【生成後のセルフレビュー（内部採点。点数は出力に含めない）】
本文を書き終えたら、出力を確定する前に自分自身で100点満点で採点すること。
評価観点: ターゲット／ベネフィット／根拠／CTA／読みやすさ／売れそうか（各観点を内部で吟味し、総合点を判断する）。
80点に満たないと判断した場合は、出力する前に自分で修正してから最終稿を確定すること。
採点結果そのものは出力に含めず、指定されたJSON構造のみを最終的に出力すること。`;
}

/**
 * 過去の成果データ(PerformanceRecord由来の要約)を戦略分析プロンプトへ
 * 渡す際の扱い方。データの有無で文言を分け、件数が少ない/無い場合は
 * 一般的なマーケティング原則を優先するよう明示する。
 */
export function buildPastPerformanceGuidance(hasData: boolean): string {
  if (!hasData) {
    return `【過去の成果データについて】
今回参考にできる過去の成果データはありません。参考データが少ないため、
一般的なマーケティング原則を優先して戦略を検討すること。`;
  }

  return `【過去の成果データの扱い方（参考情報。ユーザーメッセージ末尾に要約を記載）】
・これは参考情報であり、再現性や成果を保証するものではない
・過去に良い成果が出た戦略だからという理由だけで、同じ戦略を機械的に勧めないこと
・ターゲットの違い・媒体の違い・投稿のタイミング・オファー内容・投稿内容・計測期間の長さ・
  母数の小ささ（件数が少なく偶然の可能性がある）を必ず考慮し、
  今回の入力内容に本当に適した戦略かどうかを都度判断すること
・実績データから因果関係を断定せず、少ない母数を成功法則と決めつけないこと`;
}

/**
 * 生成物（PDF/LINE/SNS等）の整合性チェックと追加の禁止事項。
 * コンテンツ生成・部分再生成のシステムプロンプト(madanai-system-prompt.ts)専用。
 * 既存の【文章の原則】【禁止表現】と重複する項目（根拠のない数字・成果保証等）は
 * ここでは繰り返さず、そこにない観点のみを追加する。
 */
export function buildContentConsistencyChecklist(): string {
  return `【生成物の整合性チェック（内部的に確認してから出力すること）】
ターゲット → 悩み → ベネフィット → 根拠 → 構成 → CTA の流れが一貫しているか、
特にターゲットとベネフィット、ベネフィットと根拠、内容とCTAがずれていないかを確認すること。
出力前に以下を自己点検すること：
1.誰向けか明確か 2.ベネフィットが未来として伝わるか 3.根拠が不足していないか
4.抽象と具体が両方あるか 5.認知段階に合っているか 6.同じ説明を繰り返していないか
7.CTAが自然か 8.継続・リピート導線も考慮されているか 9.根拠のない断定がないか
10.マダナイが単なる制作会社に見えていないか

【追加の禁止事項】
・存在しない実績やお客様の声を作らない
・認知段階を無視して毎回同じ型を使わない
・「こんなお悩みありませんか？」を毎回機械的に使わない
・機能説明だけで終わらない
・抽象表現だけで具体性がない文章にしない
・具体情報だけで感情や未来が伝わらない文章にしない
・どの業種にも同じ文章を使い回さない
・心理学用語を権威付けのためだけに使わない`;
}
