function withIds<T extends object>(items: T[], prefix: string): (T & { id: string })[] {
  return items.map((item, index) => ({
    ...item,
    id: `${prefix}-${index}`,
  }));
}

/**
 * ContentInput から GeneratedContent のモックを組み立てる。
 * strategy は入力を反映し、pdf/line/sns/cta は固定デモコンテンツを使う
 * （Claude API未接続のため、入力ごとに本文まで作り分けることはしない）。
 * STEP3ではこの関数をClaude APIの構造化レスポンスへの変換に置き換える。
 */
export function buildMockGeneratedContent(
  id: string,
  input: ContentInput,
): GeneratedContent {
  const now = new Date().toISOString();

  return {
    id,
    createdAt: now,
    updatedAt: now,
    input,
    strategy: buildStrategyFromInput(input),
    pdf: {
      sections: withIds(FIXED_PDF_SECTIONS, `${id}-pdf`),
    },
    line: { ...FIXED_LINE },
    sns: {
      threadsPosts: withIds(FIXED_THREADS, `${id}-threads`) as [
        ThreadsPost,
        ThreadsPost,
        ThreadsPost,
      ],
      ...FIXED_SNS,
    },
    cta: buildCtaFromInput(input),
  };
}
